// Embed the factory master images from ../fm900/MASTERS, and the enhanced FM92R
// fork master built by ../firmware/extended/build.py, as a generated TS module.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '..', '..', 'fm900', 'MASTERS');
const forkDir = join(here, '..', '..', 'firmware', 'extended');
const out = join(here, '..', 'src', 'core', 'masters.gen.ts');
const lines = ['// Generated by scripts/gen-masters.mjs from fm900/MASTERS and firmware/extended. Do not edit.',
  'export const MASTERS_B64: Record<string, string> = {'];
for (const f of readdirSync(dir).filter((f) => f.toUpperCase().endsWith('.BIN')).sort()) {
  lines.push(`  ${JSON.stringify(f.toUpperCase())}: ${JSON.stringify(readFileSync(join(dir, f)).toString('base64'))},`);
}
lines.push('};', '');

// The fork masters are assembled from source (stdlib Python 3). Without Python the
// app still builds; the fork firmware options are then unavailable.
const forks = {};
try {
  execFileSync(process.env.PYTHON ?? 'python3', [join(forkDir, 'build.py')], { stdio: ['ignore', 'ignore', 'inherit'] });
  for (const [id, f] of [['enhanced', 'FM92R-fork.BIN'], ['intro', 'FM92R-intro.BIN']]) {
    const bin = join(forkDir, 'build', f);
    if (existsSync(bin)) forks[id] = readFileSync(bin).toString('base64');
  }
} catch (e) {
  console.warn(`gen-masters: could not build the FM92R fork (${e.message.split('\n')[0]}); fork firmware disabled`);
}
lines.push('/** FM92R fork masters (firmware/extended): enhanced = ident + Rx frequency, intro = ident only. */',
  `export const FORKS_B64: Record<string, string> = ${JSON.stringify(forks)};`, '');
writeFileSync(out, lines.join('\n'));
