// Embed the factory master images from ../fm900/MASTERS, and the enhanced FM92R
// fork master built by ../firmware/fork/build.py, as a generated TS module.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '..', '..', 'fm900', 'MASTERS');
const forkDir = join(here, '..', '..', 'firmware', 'fork');
const out = join(here, '..', 'src', 'core', 'masters.gen.ts');
const lines = ['// Generated by scripts/gen-masters.mjs from fm900/MASTERS and firmware/fork. Do not edit.',
  'export const MASTERS_B64: Record<string, string> = {'];
for (const f of readdirSync(dir).filter((f) => f.toUpperCase().endsWith('.BIN')).sort()) {
  lines.push(`  ${JSON.stringify(f.toUpperCase())}: ${JSON.stringify(readFileSync(join(dir, f)).toString('base64'))},`);
}
lines.push('};', '');

// The fork master is assembled from source (stdlib Python 3). Without Python the
// app still builds; the Enhanced firmware option is then unavailable.
let fork = null;
try {
  execFileSync(process.env.PYTHON ?? 'python3', [join(forkDir, 'build.py')], { stdio: ['ignore', 'ignore', 'inherit'] });
  const bin = join(forkDir, 'build', 'FM92R-fork.BIN');
  if (existsSync(bin)) fork = readFileSync(bin).toString('base64');
} catch (e) {
  console.warn(`gen-masters: could not build the FM92R fork (${e.message.split('\n')[0]}); Enhanced firmware disabled`);
}
lines.push('/** Enhanced FM92R master (firmware/fork), null if it could not be built. */',
  `export const FORK_B64: string | null = ${JSON.stringify(fork)};`, '');
writeFileSync(out, lines.join('\n'));
