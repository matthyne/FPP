// Embed the factory master images from ../fm900/MASTERS as a generated TS module.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '..', '..', 'fm900', 'MASTERS');
const out = join(here, '..', 'src', 'core', 'masters.gen.ts');
const lines = ['// Generated by scripts/gen-masters.mjs from fm900/MASTERS. Do not edit.',
  'export const MASTERS_B64: Record<string, string> = {'];
for (const f of readdirSync(dir).filter((f) => f.toUpperCase().endsWith('.BIN')).sort()) {
  lines.push(`  ${JSON.stringify(f.toUpperCase())}: ${JSON.stringify(readFileSync(join(dir, f)).toString('base64'))},`);
}
lines.push('};', '');
writeFileSync(out, lines.join('\n'));
